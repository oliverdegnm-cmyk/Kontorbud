export function categoryBySlug(slug) {
  return CATS.find((c) => c.slug === slug) || null;
}

// Finder den kategori, der bedst matcher en fritekst-søgning (f.eks. "jeg vil
// gerne have en chatbot til min hjemmeside" -> "Chatbots & AI-assistenter").
// Returnerer null, hvis intet giver mening at gætte på.
export function matchCategoryFromText(text) {
  if (!text?.trim()) return null;
  const q = text.toLowerCase();

  let best = null;
  let bestLength = 0;
  for (const cat of CATS) {
    for (const kw of cat.keywords) {
      if (q.includes(kw) && kw.length > bestLength) {
        best = cat;
        bestLength = kw.length;
      }
    }
  }
  return best;
}
